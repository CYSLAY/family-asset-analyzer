const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ?? 'playwright')
const browser = await chromium.launch({ headless: true, channel: 'chrome' })
const errors = []
try {
  const page = await browser.newPage({ acceptDownloads: true })
  page.on('pageerror', error => errors.push(error.message))
  page.on('dialog', dialog => dialog.accept())
  await page.route('**/*', route => route.request().url().startsWith('http://127.0.0.1:44002/') ? route.continue() : route.abort())
  await page.goto('http://127.0.0.1:44002/?preview')
  await page.getByRole('heading', { name: '开始进行家庭财务分析' }).waitFor()
  await page.evaluate(async () => {
    const { createCustomer } = await import('/src/types/domain.ts')
    const { setLocalWorkspace, putCustomer } = await import('/src/lib/localDb.ts')
    const { useCustomerStore } = await import('/src/stores/customerStore.ts')
    setLocalWorkspace('preview')
    const customers = Array.from({ length: 18 }, (_, i) => createCustomer(`虚构验收客户${i}`, i < 6 ? 'advisor' : 'self_service'))
    for (const customer of customers) await putCustomer(customer)
    useCustomerStore.setState({ customers, selectedCustomerId: customers[0].id, initialized: true })
  })
  await page.reload()
  await page.getByRole('button', { name: '客户自填下一页' }).waitFor()
  const topNav = () => page.locator('.sidebar .nav-list')
  const check = async (label, width) => {
    const sizes = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth }))
    if (sizes.scroll > sizes.width + 1) throw Error(`${label} overflow ${JSON.stringify(sizes)}`)
    await page.screenshot({ path: `/private/tmp/family-${label}-${width}.png`, fullPage: true })
    console.log(JSON.stringify({ label, width, overflow: false }))
  }
  for (const width of [390, 834, 1440]) {
    await page.setViewportSize({ width, height: 1000 })
    // Main navigation appears either in the sidebar or bottom bar.
    const nav = page.locator(width < 768 ? '.mobile-nav' : '.sidebar .nav-list')
    await nav.getByRole('button', { name: '客户管理', exact: true }).click()
    await check('directory', width)
    await page.getByRole('button', { name: '客户自填下一页' }).click()
    await page.getByRole('button', { name: '客户自填上一页' }).click()
    await page.locator('.customer-source-section').first().locator('.customer-main').first().click()
    for (const name of ['客户资料', '家庭成员', '固定资产', '流动资产与负债', '生活收支', '教育期望']) {
      await page.getByRole('navigation', { name: '客户资料快速切换' }).getByRole('button', { name, exact: true }).click()
      await check(`intake-${['客户资料','家庭成员','固定资产','流动资产与负债','生活收支','教育期望'].indexOf(name)}`, width)
    }
    await page.getByRole('navigation', { name: '客户资料快速切换' }).getByRole('button', { name: '分析报告', exact: true }).click()
    await page.getByText('资产结构与现金流诊断', { exact: true }).waitFor()
    await check('report', width)
    await nav.getByRole('button', { name: '现金流管理', exact: true }).click()
    await page.getByText('家庭现金流长期预测', { exact: true }).waitFor()
    await check('cashflow', width)
    await page.getByRole('button', { name: '放大表格', exact: true }).click()
    await page.getByRole('dialog').waitFor()
    await check('cashflow-fullscreen', width)
    await page.getByRole('button', { name: '关闭放大表格', exact: true }).click()
    await nav.getByRole('button', { name: '储蓄险计算', exact: true }).click()
    await page.getByRole('textbox', { name: '每年储蓄金额' }).waitFor()
    await check('insurance', width)
  }
  await page.getByRole('button', { name: '关闭隐私模式并显示客户资料' }).click()
  if (await page.getByText('我的测算方案', { exact: true }).count()) throw Error('Removed library remains visible')
  await topNav().getByRole('button', { name: '现金流管理', exact: true }).click()
  if (await page.getByRole('button', { name: /确认升级|返回原简版/ }).count()) throw Error('Legacy model switch remains visible')
  console.log('removed library and upgrade controls verified')
  await topNav().getByRole('button', { name: '客户管理', exact: true }).click()
  await page.getByText('备份与资料恢复', { exact: true }).click()
  await page.getByLabel('备份密码').fill('isolated-backup-test-only')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载加密备份' }).click()
  const file = await download; await file.saveAs('/private/tmp/family-qa-backup-encrypted.json')
  await page.getByLabel('读取备份').setInputFiles('/private/tmp/family-qa-backup-encrypted.json')
  await page.getByText(/发现 18 份资料/).waitFor()
  console.log('encrypted backup download and import preview passed')
  if (errors.length) throw Error(errors.join('\n'))
} finally { await browser.close() }
